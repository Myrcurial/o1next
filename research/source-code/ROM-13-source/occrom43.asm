DELAY:	;'N' Milliseconds
;	Entry	A=Number of Milliseconds to delay
;		SCLFRE= (Freq/1000)/25
;	Exit	Time passed.

	Proc
	PUSH	BC
	MOV	C,A
:1:	LDK	A,SCLFRE
 
:2:	DEC	A	;(4 tics)
	MOV	B,B	;(4 tics)
	MOV	C,C	;(4 tics)
	JNZ	:2	;(10 tics) If 1 ms not elapsed
	DEC	C
	JNZ	:1	;If requested msec not done
	POP	BC	;restore registers
	RET

