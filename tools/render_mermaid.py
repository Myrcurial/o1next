#!/usr/bin/env python3
"""render_mermaid.py - render the site's Mermaid diagrams to PNG.

WHY THIS EXISTS
    A Mermaid block in a post does not render.  Mermaid's `startOnLoad` looks for
    elements with class `mermaid`, and a kramdown code fence produces
    `<pre><code class="language-mermaid">`, which it never matches -- so the
    diagram ships as a code block and looks broken.  The first attempt at a fix
    was a loader in `_layouts/default.html`; it loaded Mermaid and nothing
    happened, for exactly that reason.

    So the diagrams are rendered here, at build time, and committed as PNGs.
    That also matches how the rest of the site's artwork works (the wordmark, the
    O1 art are both generated) and keeps the page's no-script character.

    The compendium's chapter pages are generated by `tools/build_book.py` and
    cannot be hand-edited, so they keep their Mermaid blocks and rely on the
    loader in the layout instead.  See site/README.md.

TYPE AND COLOUR
    The diagrams are set in the Osborne 1's own character generator at the
    80-column width -- the same face the page is set in, from
    `site/assets/fonts/osborne1-80.ttf` -- and use the palette
    `site/assets/main.css` records.

    Chrome has to be able to *see* the font by family name, and a `@font-face`
    passed through mermaid-cli's `--cssFile` is not enough.  So the script checks
    for the font and tells you where to put it; it does not install it for you.

    tools/render_mermaid.py [--scale N] [--only NAME]
"""
import base64
import json
import os
import shutil
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = os.path.join(REPO, 'site')
DIAGRAMS = os.path.join(SITE, 'assets', 'diagrams')
ASSETS = os.path.join(SITE, 'assets')
FONT_NAME = 'Osborne 1 80'
FONT_SRC = os.path.join(ASSETS, 'fonts', 'osborne1-80.ttf')
FONT_INSTALLED = os.path.expanduser('~/Library/Fonts/osborne1-80.ttf')

# The site palette, from site/assets/main.css.
CODE = '#16191c'      # --grey-soft: what a code block uses, and the diagram's ground
INK = '#e9e7e0'       # --ink
BLUE = '#687898'      # --blue, the front panel
BLUE_INK = '#2b3547'  # --blue-ink
RULE = '#2b3034'      # --rule


def mmdc():
    """mermaid-cli, from the repo's .venv-style local install or PATH."""
    for c in (os.environ.get('MMDC'),
              os.path.join(REPO, '.venv', 'node_modules', '.bin', 'mmdc'),
              shutil.which('mmdc')):
        if c and os.path.exists(c):
            return c
    return None


def build_css(path):
    """The diagram's type, embedded.

    `-C cssFile` is what actually applies this -- a font installed in
    ~/Library/Fonts does not do it, which is worth knowing because it looks like
    it should.  Embedding also keeps the render self-contained: nothing has to be
    installed on the machine for the diagrams to come out in the machine's own
    face.
    """
    with open(FONT_SRC, 'rb') as fh:
        b64 = base64.b64encode(fh.read()).decode()
    open(path, 'w').write(
        '@font-face {\n'
        '  font-family: "%s";\n'
        '  src: url(data:font/ttf;base64,%s) format("truetype");\n'
        '}\n'
        'svg, .nodeLabel, .edgeLabel, .label, span, div, text {\n'
        '  font-family: "%s" !important;\n'
        '}\n' % (FONT_NAME, b64, FONT_NAME))


def build_config(path):
    json.dump({
        'theme': 'base',
        'themeVariables': {
            'fontFamily': FONT_NAME,
            'fontSize': '20px',
            'background': CODE,
            'primaryColor': BLUE_INK, 'primaryTextColor': INK,
            'primaryBorderColor': BLUE,
            'secondaryColor': '#22303f', 'secondaryTextColor': INK,
            'secondaryBorderColor': BLUE,
            'tertiaryColor': '#1b1f23', 'tertiaryTextColor': INK,
            'tertiaryBorderColor': RULE,
            'lineColor': BLUE, 'textColor': INK,
            'edgeLabelBackground': CODE,
            'clusterBkg': '#12161a', 'clusterBorder': BLUE,
            'titleColor': INK,
        },
        'flowchart': {'curve': 'basis', 'nodeSpacing': 45, 'rankSpacing': 55,
                      'padding': 12, 'useMaxWidth': False},
    }, open(path, 'w'), indent=1)


def chrome():
    """Chrome, for puppeteer to drive.  mmdc's bundled browser is not downloaded
    here, and without a puppeteer config pointing at a real Chrome the render
    takes a path where the embedded font is *not* applied -- the diagrams come out
    in a serif face while looking otherwise fine, which is easy to miss."""
    for c in (os.environ.get('CHROME_PATH'),
              '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
              '/Applications/Chromium.app/Contents/MacOS/Chromium',
              '/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge',
              shutil.which('google-chrome'), shutil.which('chromium')):
        if c and os.path.exists(c):
            return c
    return None


def build_puppeteer(path):
    json.dump({'executablePath': chrome(),
               'args': ['--no-sandbox', '--disable-gpu']},
              open(path, 'w'), indent=1)


def main(argv):
    scale = '2'
    only = None
    for i, a in enumerate(argv):
        if a == '--scale':
            scale = argv[i + 1]
        if a == '--only':
            only = argv[i + 1]

    tool = mmdc()
    if not tool:
        print('mmdc (mermaid-cli) not found.  See REQUIREMENTS.md.')
        return 1
    if not os.path.exists(FONT_SRC):
        print('Missing %s -- the diagram type comes from it.' % FONT_SRC)
        return 1
    # The embedded @font-face alone is not enough: without the face installed,
    # Chrome half-loads it and renders every glyph as a tofu box, with the right
    # metrics -- which reads as "the font worked" in a file listing.  So: check,
    # do not hope.
    if not os.path.exists(FONT_INSTALLED):
        print('The diagram type is %r and Chrome cannot see it.' % FONT_NAME)
        print('Install it once (user-scoped, reversible), then re-run:')
        print('    cp %s ~/Library/Fonts/' % FONT_SRC)
        return 1
    if not chrome():
        print('No Chrome found for puppeteer.  Set CHROME_PATH, or see')
        print('REQUIREMENTS.md.  Without it the diagrams render in the wrong face.')
        return 1

    cfg = '/tmp/o1ng-mermaid-config.json'
    css = '/tmp/o1ng-mermaid-style.css'
    pp = '/tmp/o1ng-mermaid-puppeteer.json'
    build_config(cfg)
    build_css(css)
    build_puppeteer(pp)

    names = sorted(f[:-4] for f in os.listdir(DIAGRAMS) if f.endswith('.mmd'))
    if only:
        names = [n for n in names if n == only]
    rc = 0
    for name in names:
        src = os.path.join(DIAGRAMS, name + '.mmd')
        out = os.path.join(ASSETS, name + '.png')
        # No --size: it caps the canvas and *clips* wide labels rather than
        # scaling them, which silently truncated `bankswitch_w` and `SCSI-1
        # target` on the first attempt.  The PNG takes the diagram's own size.
        r = subprocess.run([tool, '-i', src, '-o', out, '-c', cfg, '-C', css,
                            '-b', CODE, '-s', scale, '-p', pp],
                           capture_output=True, text=True)
        ok = r.returncode == 0 and os.path.exists(out)
        print('%-34s %s' % (name + '.png',
                            'rendered' if ok else 'FAILED\n' + r.stderr[-800:]))
        rc |= 0 if ok else 1
    return rc


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
